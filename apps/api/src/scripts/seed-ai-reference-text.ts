async function main() {
  let updated = 0;
  let notFound = 0;

  for (const [description, referenceText] of Object.entries(REFERENCE_TEXT_BY_DESCRIPTION)) {
    const result = await prisma.probyPoint.updateMany({
      where: { description },
      data: { referenceText },
    });
    if (result.count === 0) {
      notFound++;
      console.warn(`No point found with description: "${description.slice(0, 60)}..."`);
    } else {
      updated += result.count;
    }
  }

  console.log(`Updated referenceText on ${updated} point row(s). ${notFound} description(s) matched nothing.`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

